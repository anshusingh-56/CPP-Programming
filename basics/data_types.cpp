#include <iostream>
using namespace std;

int main ()
{
    int a = 19;
    float b = 85.7;
    double c = 20.55;
    char d = 'A';
    bool e = true;

    cout<<"Integer = "<<a<<endl;
    cout<<"Float = "<<b<<endl;
    cout<<"Double = "<<c<<endl;
    cout<<"Character = "<<d<<endl;
    cout<<"Boolean = "<<e<<endl;

    return 0;
}